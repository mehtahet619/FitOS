import { danger, fail, markdown, message, warn } from "danger";
import fs from "node:fs";
import path from "node:path";

const workspaceRoot = process.env.GITHUB_WORKSPACE || path.resolve(process.cwd(), "..");
const policyPath = path.join(workspaceRoot, ".github/review-policy.yml");
const policyText = fs.existsSync(policyPath) ? fs.readFileSync(policyPath, "utf8") : "";
const sensitiveSection = policyText.split("maintainers:")[0];
const sensitivePatterns = sensitiveSection
  .split("\n")
  .filter((line) => line.trim().startsWith("- \""))
  .map((line) => line.trim().slice(3, -1));

const files = [...danger.git.modified_files, ...danger.git.created_files, ...danger.git.deleted_files];
const linesChanged = danger.github.pr.additions + danger.github.pr.deletions;
const matches = (file: string, pattern: string) => {
  const escaped = pattern.replace(/[.+?^${}()|[\]\\]/g, "\\$&");
  const doubleStar = "__DOUBLE_STAR__";
  const regexSource = escaped
    .replaceAll("**", doubleStar)
    .replaceAll("*", "[^/]*")
    .replaceAll(doubleStar, ".*");
  return new RegExp(`^${regexSource}$`).test(file);
};
const sensitiveFiles = files.filter((file) => sensitivePatterns.some((pattern) => matches(file, pattern)));
const logicFiles = files.filter((file) => /\.(ts|tsx|js|jsx)$/.test(file) && !/\.test\.|__tests__/.test(file));
const testFiles = files.filter((file) => /\.(test|spec)\.(ts|tsx|js|jsx)$/.test(file) || file.includes("__tests__"));
const requiredChecks = ["lint", "typecheck", "test", "build", "codeql", "secretlint"];
const checkRuns = await danger.github.api.checks.listForRef({
  owner: danger.github.repository.organization || danger.github.repository.owner,
  repo: danger.github.repository.name,
  ref: danger.github.pr.head.sha,
});
const latestChecks = new Map<string, { conclusion?: string | null; status?: string | null }>(
  checkRuns.data.check_runs.map((check) => [check.name, { conclusion: check.conclusion, status: check.status }]),
);
const checkSummary = requiredChecks
  .map((checkName) => {
    const check = latestChecks.get(checkName);
    return `- ${checkName}: **${check?.conclusion || check?.status || "not found"}**`;
  })
  .join("\n");

const title = danger.github.pr.title;
if (!/^\[[A-Z][A-Z0-9-]*\]\s+\S+/.test(title)) {
  fail("PR title must use the required `[TAG] description` format.");
}
if (linesChanged > 400) warn(`This PR changes ${linesChanged} lines and may be hard to review.`);
if (sensitiveFiles.length) {
  warn(`Sensitive paths changed: ${sensitiveFiles.join(", ")}. Human approval is required; auto-merge is disabled.`);
}
if (logicFiles.length && !testFiles.length) {
  fail("New logic files were changed without adding or updating a test file.");
}

markdown(`## Automated review\n\n### Required checks\n${checkSummary}\n\n- Files changed: **${files.length}**\n- Lines changed: **${linesChanged}**\n- Sensitive paths: **${sensitiveFiles.length ? sensitiveFiles.join(", ") : "none"}**\n- Test files changed: **${testFiles.length}**\n\nMechanical ESLint findings are posted as GitHub suggestions when a safe autofix is available. CodeQL findings appear as security annotations and require human review; they are not auto-fixed.`);
message("No paid AI API is used by this review bot. Feedback is generated by static analysis and Danger rules.");